# SOLID software design principles :->

# s -> single responsibility principle
# we should use the class and object for a purpose so we should follow single responsibility principle
# 1 class 1 object should contain one responsibility

# o -> open closed principle
# open for extension (we can add new things, but we should not change the code)
# closed for modification (already used code should not modify the code)

# L -> Liskov substitution principle
# objects of a superclass should be replaceable with
# objects of a subclass without breaking the application or changing expected behavior.

# I - Interface segregation principle
# mostly not used in python because it doesn't allow multiple inheritance
# should not use unused abstract class

# D -> Dependency Inversion principle
# we should not keep complete dependency for all
# High-level modules should not depend on low-level modules